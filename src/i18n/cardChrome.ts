const CHROME: Record<SupportedLanguage, ChromeMaps> = {
    fr,
    en,
    de,
    it,
    es,
};

function pick(
    map: Record<string, string>,
    key: string | undefined | null
): string | null {
    if (!key) return null;
    return map[key] || key;
}

export function getCardChrome(lang: SupportedLanguage) {
    const maps = CHROME[lang] ?? CHROME.fr;
    return {
        home: maps.home,
        or: maps.or,
        type: (key?: string | null) => pick(maps.type, key),
        subtype: (key?: string | null) => pick(maps.subtype, key),
        race: (key?: string | null) => pick(maps.race, key),
        phase: (key?: string | null) => pick(maps.phase, key),
    };
}
